import { writeFileSync } from "node:fs";
const code = [
'#!/usr/bin/env node',
'/**',
' * markdown.mjs --- Frontmatter/Markdown parser and DNT patterns.',
' */',
'import { load as yamlLoad, dump as yamlDump } from "js-yaml";',
'export const DNT_PATTERNS = {',
'  grades: [',
'    /\\bGrade\\s+\\d+[A-Z]?\\b/g,',
'    /\\bTi-\\d+[A-Za-z0-9-]+\\b/g,',
'    /\\b(?:UNS\\s+)?R\\d{4,6}\\b/g,',
'    /\\b(?:CP-)?Ti\\s*(?:Grade\\s+)?\\d\\b/g,',
'  ],',
'  standards: [',
'    /\\bASTM\\s+[A-Z]\\d+(?:\\/\\d+)?(?:-\\d+)?\\b/g,',
'    /\\bAMS\\s+\\d{4}[A-Z]?\\b/g,',
'    /\\bISO\\s+\\d+(?:-\\d+)?\\b/g,',
'    /\\bMIL-(?:STD|PRF|SPEC)-\\d+[A-Z]?\\b/g,',
'    /\\bSAE\\s+(?:AMS\\s+)?\\d+[A-Z]?\\b/g,',
'    /\\bEN\\s+\\d+(?:-\\d+)?\\b/g,',
'    new RegExp("\\\\bGB\\\\/T\\\\s+\\\\d+(?:\\\\.\\\\d+)?(?:-\\\\d+)?\\\\b", "g"),',
'    /\\bJIS\\s+[A-Z]+\\s+\\d+\\b/g,',
'    /\\bDIN\\s+(?:EN\\s+)?\\d+(?:-\\d+)?\\b/g,',
'  ],',
'  units: [',
'    /\\b(?:\\u00b5m|\\u03bcm|nm|mm|cm|m|km)\\b/g,',
'    /\\b(?:\\u00b0C|\\u00b0F|K)\\b/g,',
'    /\\b(?:MPa|ksi|GPa|Pa|psi|N\\/mm\\u00b2)\\b/g,',
'    /\\b(?:%|wt\\.?\\s*%|at\\.?\\s*%)\\b/g,',
'    /\\b(?:HR[BC]|HV|HB|HRC)\\b/g,',
'  ],',
'  parameters: [',
'    /\\b(?:MTR|MTC|NDT|UT|ET|MT|PT|RT|MPI|FPI)\\b/g,',
'    /\\b(?:HIP|EDM|CVD|PVD|EBM|DED|SLM|L-PBF)\\b/g,',
'    /\\b(?:OEE|UTS|YS|EL|RA|FAT|SD|SCC|HE|HIC|SOHIC)\\b/g,',
'  ],',
'};',
'export const DNT_COMBINED = new RegExp(',
'  Object.values(DNT_PATTERNS).flat().map(function(r) { return r.source; }).join("|"), "g");',
'export function splitFrontmatter(raw) {',
'  if (!raw.startsWith("---")) return { frontmatterRaw: null, body: raw };',
'  const endIdx = raw.indexOf("---", 3);',
'  if (endIdx === -1) return { frontmatterRaw: null, body: raw };',
'  return { frontmatterRaw: raw.slice(3, endIdx).trim(), body: raw.slice(endIdx + 3).trim() };',
'}',
'export function parseFrontmatter(yamlStr) {',
'  if (!yamlStr) return {};',
'  try { return yamlLoad(yamlStr) || {}; } catch { return {}; }',
'}',
'export function serializeFrontmatter(obj) {',
'  const dumped = yamlDump(obj, { lineWidth: -1, noRefs: true, quotingType: "\'" });',
'  return dumped.endsWith("\\n") ? dumped : dumped + "\\n";',
'}',
'export function collectStrings(obj) {',
'  const strings = [];',
'  function walk(node, path) {',
'    if (typeof node === "string") {',
'      if (/^\\d+(\\.\\d+)?$/.test(node)) return;',
'      if (/^[A-Z_]{2,}$/.test(node)) return;',
'      if (/^https?:\\/\\//.test(node)) return;',
'      if (node.length < 2) return;',
'      strings.push({ path: path, value: node });',
'    } else if (Array.isArray(node)) {',
'      node.forEach(function(item, i) { walk(item, path.concat(String(i))); });',
'    } else if (node && typeof node === "object") {',
'      for (const key of Object.keys(node)) { walk(node[key], path.concat(key)); }',
'    }',
'  }',
'  walk(obj, []);',
'  return strings;',
'}',
'export function setByPath(obj, path, value) {',
'  let current = obj;',
'  for (let i = 0; i < path.length - 1; i++) {',
'    if (!(path[i] in current)) current[path[i]] = {};',
'    current = current[path[i]];',
'  }',
'  current[path[path.length - 1]] = value;',
'}',
'export function extractDNT(text) {',
'  const tokens = new Set();',
'  const matches = text.matchAll(DNT_COMBINED);',
'  for (const m of matches) { tokens.add(m[0].trim()); }',
'  return [...tokens].sort();',
'}',
'export function checkDNT(source, translated) {',
'  const dntTokens = extractDNT(source);',
'  const missing = [];',
'  const violations = [];',
'  for (const token of dntTokens) {',
'    const escaped = token.replace(/[.*+?^${}()|[\\]\\\\]/g, "\\\\$&");',
'    const regex = new RegExp(escaped, "g");',
'    const found = translated.match(regex);',
'    if (!found) {',
'      if (/\\d+/.test(token)) {',
'        const numericPart = token.match(/\\d+[A-Z]?/)[0];',
'        if (translated.includes(numericPart)) {',
'          violations.push({ expected: token, found: "partial match: " + numericPart });',
'        } else { missing.push(token); }',
'      } else { missing.push(token); }',
'    }',
'  }',
'  return { pass: missing.length === 0 && violations.length === 0, missing: missing, violations: violations };',
'}',
'export default { DNT_PATTERNS, DNT_COMBINED, splitFrontmatter, parseFrontmatter, serializeFrontmatter, collectStrings, setByPath, extractDNT, checkDNT };',
].join('\n');
writeFileSync("scripts/lib/markdown.mjs", code, "utf8");
console.log("Generated markdown.mjs");